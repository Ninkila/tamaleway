export function computeCareerRankTitle(
  profile: PlayableCharacterProfile,
  completedJobs: number,
  cultureXp: number
): { tier: number; title: string } {
  const score = completedJobs * 25 + cultureXp;
  if (score >= 450) return { tier: 5, title: `Master ${profile.occupation}` };
  if (score >= 280) return { tier: 4, title: `Senior ${profile.occupation}` };
  if (score >= 160) return { tier: 3, title: `Trusted ${profile.occupation}` };
  if (score >= 70) return { tier: 2, title: `Active ${profile.occupation}` };
  return { tier: 1, title: profile.occupation };
}

