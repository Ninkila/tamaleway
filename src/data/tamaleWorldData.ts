export function getDistrictAt(x: number, z: number): string {
  if (Math.hypot(x, z) < 28) return "Naa Gbewaa Interchange · Dagbandabo Fong";
  let closestName = "Central Tamale";
  let bestDist = Infinity;
  for (const comm of TAMALE_COMMUNITIES) {
    const d = Math.hypot(x - comm.x, z - comm.z);
    if (d < comm.radius && d < bestDist) {
      bestDist = d;
      closestName = comm.name;
    }
  }
  return closestName;
}
