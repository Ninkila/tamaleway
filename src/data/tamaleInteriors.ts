function createShopFallbackInterior(landmarkId: string): InteriorRoomSpec {
  const lm = TAMALE_LANDMARKS.find((l) => l.id === landmarkId);
  const title = lm?.interiorTitle || lm?.name || "Tamale Building Interior";
  const dagbaniTitle = lm?.dagbaniLabel || "Duɣu Puuni";
  const shopId = lm?.shopId;

  let archetype: InteriorRoomSpec["archetype"] = "market_hall";
  let stations: InteriorRoomSpec["stations"] = [
    { id: "exit", kind: "exit_door", label: "Step Back Outside", dagbaniLabel: "Yi Kpaŋa", x: 0, z: 4.4, radius: 1.8 },
    { id: "counter", kind: "shelf_browse", label: `Browse ${lm?.name ?? "Shop"} Goods`, dagbaniLabel: "Da Nɛma", x: 0, z: -2.4, radius: 2.6 },
  ];

  if (landmarkId.includes("fashion") || landmarkId.includes("footwear") || landmarkId.includes("tailor")) {
    archetype = "barber_salon";
    stations = [
      { id: "exit", kind: "exit_door", label: "Exit Boutique to Street", dagbaniLabel: "Yi Kpaŋa", x: 0, z: 4.4, radius: 1.8 },
      { id: "rack", kind: "shelf_browse", label: "Browse Clothing, Footwear & Accessories", dagbaniLabel: "Lihi Nɛma", x: -2.4, z: -2.2, radius: 2.5 },
      { id: "wardrobe", kind: "wardrobe", label: "Fitting Mirror & Outfit Try-On", dagbaniLabel: "Yɛ Nɛma", x: 2.8, z: -1.8, radius: 2.2 },
    ];
  } else if (landmarkId.includes("student_hub")) {
    archetype = "pharmacy_bakery";
    stations = [
      { id: "exit", kind: "exit_door", label: "Exit Café to Dungu Avenue", dagbaniLabel: "Yi Kpaŋa", x: 0, z: 4.4, radius: 1.8 },
      { id: "cafe_counter", kind: "food_counter", label: "Order Waakye, Drinks & Print Services", dagbaniLabel: "Bindirigu", x: -2.0, z: -2.4, radius: 2.4 },
      { id: "table", kind: "dining_table", label: "Student Study & Dining Table", dagbaniLabel: "Karimbu Teebuli", x: 3.2, z: 0.4, radius: 2.2 },
    ];
  }

  return {
    landmarkId,
    archetype,
    title,
    dagbaniTitle,
    width: 12.5,
    depth: 10.5,
    height: 3.8,
    wallColor: "#f5f5f4",
    floorColor: "#a8a29e",
    accentColor: "#d97706",
    ceilingColor: "#e7e5e4",
    ambientHex: "#fef3c7",
    spawnX: 0,
    spawnZ: 3.5,
    shopId,
    hasIndoorRadio: true,
    stations,
  };
}

export function getInteriorSpecForLandmark(landmarkId: string): InteriorRoomSpec | null {
  if (INTERIOR_ROOMS[landmarkId]) {
    return INTERIOR_ROOMS[landmarkId];
  }
  const lm = TAMALE_LANDMARKS.find((l) => l.id === landmarkId);
  if (!lm || !lm.enterable) return null;
  return createShopFallbackInterior(landmarkId);
}
