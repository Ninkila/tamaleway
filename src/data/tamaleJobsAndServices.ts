export function calculateServiceFare(
  entry: ServiceCatalogEntry,
  distanceMeters: number,
  packageExtraCedis = 0
): number {
  const km = Math.max(0.25, distanceMeters / 1000);
  return Math.round(entry.baseFareCedis + entry.perKmCedis * km + packageExtraCedis);
}
